"""Regenerates the evaluation files from a saved analysis.  Run: py scripts/make_gate3_reports.py <session_id> [n_configurations]

Writes to the project root: weight_scenario_comparison.csv, merchant_rank_stability.csv, top15_overlap_matrix.csv, manual_validation_log.csv,
weight_sensitivity_report.md, failure_analysis.md, evaluation_summary.md, limitations.md and configuration_snapshot.json.
Every number comes from the saved analysis; the text is generated by api/evaluation.py, the same code that builds the in-app evaluation package.
"""
import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))

from api import ai_disclosure, evaluation, exporter, store, validation, weights  # noqa: E402
from src.config import load_scoring  # noqa: E402

sid = sys.argv[1]
n = int(sys.argv[2]) if len(sys.argv) > 2 else 300
s, st = store.load_session(sid), store.load_state(sid)
base = weights.apply_overrides(load_scoring(), s.get("scoring_overrides"))
stab = weights.stability(store.load_frame(sid), base, s["assumptions"], weights.playbook_frame(s["playbooks"]), int(s["kpis"]["capacity"]), n)
store.save_extra(sid, "stability", stab)
val = validation.build(s, stab, st.get("validation"))
ai = ai_disclosure.build(s, store.load_extra(sid, "ask_log") or [], False, "")
extra = {"stability": stab, "validation": val}

for kind, fname in (("weight_scenarios", "weight_scenario_comparison.csv"), ("stability", "merchant_rank_stability.csv"), ("overlap", "top15_overlap_matrix.csv"), ("validation", "manual_validation_log.csv")):
    (ROOT / fname).write_bytes(exporter.to_csv(kind, s, st, extra))
(ROOT / "weight_sensitivity_report.md").write_text(evaluation.weight_report_md(s, stab), encoding="utf-8")
(ROOT / "failure_analysis.md").write_text(evaluation.failure_md(s, val, stab), encoding="utf-8")
(ROOT / "evaluation_summary.md").write_text(evaluation.summary_md(s, stab, val, ai), encoding="utf-8")
(ROOT / "limitations.md").write_text(evaluation.limitations_md(), encoding="utf-8")
(ROOT / "configuration_snapshot.json").write_text(json.dumps(evaluation.config_snapshot(s), indent=2, default=str), encoding="utf-8")
print("wrote evaluation files for", sid, stab["counts"], val["summary"])
